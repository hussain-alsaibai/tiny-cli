"""Shell completion for tiny-cli Apps.

Generate bash/zsh/fish completion scripts from a registered tiny-cli App,
or install them into the standard XDG locations.

Stdlib-only. Zero deps.

Usage:
    from tiny_cli import App
    from tiny_cli.completion import ShellCompletion

    app = App(name="myapp")
    @app.command()
    def deploy(env: str = "dev"): ...

    sc = ShellCompletion(app)
    # Print a bash completion script to stdout
    print(sc.emit_bash())
    # Or install for the current user
    sc.install("bash")  # writes to $XDG_DATA_HOME/bash-completion/completions/myapp
"""

from __future__ import annotations

import os
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

__all__ = ["ShellCompletion"]


class ShellCompletion:
    """Generate and install shell completion scripts for a tiny-cli App.

    Args:
        app: A tiny-cli App with registered commands.
        bind: Name of the completion function (default: app.name).
            The bash script registers a function named ``_<bind>``, and
            ``complete -F _<bind> <prog>`` makes it active.
        shells: Sequence of supported shells. Default: ("bash", "zsh", "fish").
    """

    _SUPPORTED_SHELLS = ("bash", "zsh", "fish")

    def __init__(
        self,
        app: Any,
        *,
        bind: Optional[str] = None,
        shells: Sequence[str] = ("bash", "zsh", "fish"),
    ) -> None:
        self.app = app
        self.prog = app.name
        self.bind = bind or app.name.replace("-", "_")
        unknown = [s for s in shells if s not in self._SUPPORTED_SHELLS]
        if unknown:
            raise ValueError(f"unsupported shell(s): {unknown!r}; expected one of {self._SUPPORTED_SHELLS}")
        self.shells = tuple(shells)

    # ---- Manifest (shared by all shell renderers) ----------------------

    def _manifest(self) -> List[Dict[str, Any]]:
        """Build a serializable manifest: list of {name, options, positionals}."""
        out: List[Dict[str, Any]] = []
        for cmd_name, fn in self.app._commands.items():  # type: ignore[attr-defined]
            help_text = (getattr(fn, "__tiny_cli_help__", "") or "").strip().split("\n")[0]
            opts: List[Dict[str, Any]] = []
            positionals: List[Dict[str, Any]] = []
            sig = __import__("inspect").signature(fn)
            for pname, param in sig.parameters.items():
                if pname == "self":
                    continue
                default = param.default
                if isinstance(default, dict) and default.get("_kind") == "option":
                    opts.append({
                        "flags": list(default["flags"]),
                        "help": default.get("help", ""),
                        "type": default.get("type", str).__name__ if hasattr(default.get("type", str), "__name__") else "str",
                        "choices": default.get("choices"),
                    })
                elif isinstance(default, dict) and default.get("_kind") == "argument":
                    positionals.append({
                        "name": default["name"],
                        "choices": default.get("choices"),
                    })
                else:
                    # Plain positional parameter
                    positionals.append({
                        "name": pname,
                        "choices": None,
                    })
            out.append({
                "name": cmd_name,
                "help": help_text,
                "options": opts,
                "positionals": positionals,
            })
        return out

    # ---- Bash ---------------------------------------------------------

    def emit_bash(self) -> str:
        """Emit a bash completion script."""
        lines: List[str] = []
        lines.append(f"# bash completion for {self.prog}")
        lines.append(f"# auto-generated by tiny-cli v{__import__('tiny_cli').__version__}")
        lines.append("")
        lines.append(f"_{self.bind}() {{")
        lines.append("    local cur prev words cword")
        lines.append("    _init_completion || return")
        lines.append("")
        lines.append(f"    local prog=\"{self.prog}\"")
        lines.append("    local commands=\"\"")
        for entry in self._manifest():
            lines.append(f"    commands=\"$commands {entry['name']}\"")
        lines.append("")
        # If user is on the first word, offer commands
        lines.append("    if [[ $cword -eq 1 ]]; then")
        lines.append("        COMPREPLY=($(compgen -W \"$commands\" -- \"$cur\"))")
        lines.append("        return")
        lines.append("    fi")
        lines.append("")
        # Find the active subcommand (first word after prog)
        lines.append("    local cmd=\"${words[1]}\"")
        lines.append("    case \"$cmd\" in")
        for entry in self._manifest():
            lines.append(f"        {entry['name']})")
            # Collect option flags
            opt_flags: List[str] = []
            for opt in entry["options"]:
                for flag in opt["flags"]:
                    if flag.startswith("--"):
                        opt_flags.append(flag)
                    elif flag.startswith("-"):
                        opt_flags.append(flag)
            if opt_flags:
                lines.append(f"            local opts=\"{' '.join(opt_flags)}\"")
                lines.append("            if [[ $cur == -* ]]; then")
                lines.append("                COMPREPLY=($(compgen -W \"$opts\" -- \"$cur\"))")
                lines.append("                return")
                lines.append("            fi")
            # Collect positionals with choices
            pos_choices = [(p["name"], p["choices"]) for p in entry["positionals"] if p["choices"]]
            if pos_choices:
                for name, choices in pos_choices:
                    lines.append(f"            if [[ $cur != -* && -z \"${{{'{' + name + '_seen'}}}\" ]]; then")
                    lines.append(f"                COMPREPLY=($(compgen -W \"{' '.join(choices)}\" -- \"$cur\"))")
                    lines.append("                return")
                    lines.append("            fi")
            lines.append("            ;;")
        lines.append("        *)")
        lines.append("            COMPREPLY=()")
        lines.append("            ;;")
        lines.append("    esac")
        lines.append("}")
        lines.append("")
        lines.append(f"complete -F _{self.bind} {self.prog}")
        lines.append("")
        return "\n".join(lines)

    # ---- Zsh ----------------------------------------------------------

    def emit_zsh(self) -> str:
        """Emit a zsh completion script."""
        lines: List[str] = []
        lines.append(f"#compdef {self.prog}")
        lines.append(f"# zsh completion for {self.prog}")
        lines.append(f"# auto-generated by tiny-cli v{__import__('tiny_cli').__version__}")
        lines.append("")
        lines.append(f"_{self.bind}() {{")
        lines.append("    local -a commands")
        for entry in self._manifest():
            lines.append(f"    commands+=({entry['name']}:{(entry['help'] or '').strip()})")
        lines.append("")
        lines.append("    _arguments -C \\")
        lines.append("        '1: :->cmd' \\")
        lines.append("        '*::arg:->args'")
        lines.append("")
        lines.append("    case $state in")
        lines.append("        cmd)")
        lines.append("            _describe 'command' commands")
        lines.append("            ;;")
        lines.append("        args)")
        lines.append("            case $words[1] in")
        for entry in self._manifest():
            lines.append(f"                {entry['name']})")
            sub_lines: List[str] = []
            for opt in entry["options"]:
                flag = next((f for f in opt["flags"] if f.startswith("--")), opt["flags"][0])
                short = next((f for f in opt["flags"] if f.startswith("-") and not f.startswith("--")), None)
                completion = "()" if not opt["choices"] else f"({' '.join(opt['choices'])})"
                if short:
                    sub_lines.append(f"                    '({flag} {short}){flag}[{opt['help']}]:value:{completion}'")
                else:
                    sub_lines.append(f"                    '{flag}[{opt['help']}]:value:{completion}'")
            for pos in entry["positionals"]:
                completion = "()" if not pos["choices"] else f"({' '.join(pos['choices'])})"
                sub_lines.append(f"                    '*:{pos['name']}:{completion}'")
            if sub_lines:
                lines.extend(sub_lines)
            else:
                lines.append("                    ;;")
            lines.append("                    ;;")
        lines.append("            esac")
        lines.append("            ;;")
        lines.append("    esac")
        lines.append("}")
        lines.append("")
        lines.append(f"compdef _{self.bind} {self.prog}")
        lines.append("")
        return "\n".join(lines)

    # ---- Fish ---------------------------------------------------------

    def emit_fish(self) -> str:
        """Emit a fish completion script."""
        lines: List[str] = []
        lines.append(f"# fish completion for {self.prog}")
        lines.append(f"# auto-generated by tiny-cli v{__import__('tiny_cli').__version__}")
        lines.append("")
        # Subcommand completions
        for entry in self._manifest():
            help_text = (entry["help"] or "").strip()
            # Fish doesn't allow newlines in completion descriptions; replace with space
            help_text = help_text.replace("\n", " ").replace("'", "\\'")
            lines.append(f"complete -c {self.prog} -n '__fish_use_subcommand' -a {entry['name']} -d '{help_text}'")
            for opt in entry["options"]:
                # Use the longest flag for the long form, shortest for short
                long_flag = next((f for f in opt["flags"] if f.startswith("--")), opt["flags"][0])
                short_flag = next((f for f in opt["flags"] if len(f) == 2 and f.startswith("-")), None)
                flag_strs = [long_flag]
                if short_flag:
                    flag_strs.append(short_flag)
                help_text = opt.get("help", "").replace("'", "\\'").replace("\n", " ")
                if opt["choices"]:
                    flag_str = " ".join(flag_strs)
                    lines.append(
                        f"complete -c {self.prog} -n '__fish_seen_subcommand_from {entry['name']}' "
                        f"-l {long_flag.lstrip('-')} " + (f"-s {short_flag.lstrip('-')} " if short_flag else "") +
                        f"-r -a \"{' '.join(opt['choices'])}\" -d '{help_text}'"
                    )
                else:
                    if opt["type"] == "bool":
                        lines.append(
                            f"complete -c {self.prog} -n '__fish_seen_subcommand_from {entry['name']}' "
                            f"-l {long_flag.lstrip('-')} " + (f"-s {short_flag.lstrip('-')} " if short_flag else "") +
                            f"-d '{help_text}'"
                        )
                    else:
                        lines.append(
                            f"complete -c {self.prog} -n '__fish_seen_subcommand_from {entry['name']}' "
                            f"-l {long_flag.lstrip('-')} " + (f"-s {short_flag.lstrip('-')} " if short_flag else "") +
                            f"-r -d '{help_text}'"
                        )
            for pos in entry["positionals"]:
                if pos["choices"]:
                    lines.append(
                        f"complete -c {self.prog} -n '__fish_seen_subcommand_from {entry['name']}' "
                        f"-a \"{' '.join(pos['choices'])}\""
                    )
        lines.append("")
        return "\n".join(lines)

    # ---- Install ------------------------------------------------------

    def install(
        self,
        shell: str,
        *,
        dest_dir: Optional[Path] = None,
        overwrite: bool = False,
    ) -> Path:
        """Write the completion script to a standard XDG location.

        bash: $XDG_DATA_HOME/bash-completion/completions/<prog>   (or ~/.local/share/...)
        zsh:  $XDG_DATA_HOME/zsh/site-functions/_<prog>           (then add to $fpath)
        fish: $XDG_DATA_HOME/fish/vendor_completions.d/<prog>.fish

        Returns the path written.
        """
        if shell not in self._SUPPORTED_SHELLS:
            raise ValueError(f"unsupported shell: {shell!r}")
        xdg = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local" / "share"))
        if dest_dir is not None:
            base = Path(dest_dir)
        else:
            base = xdg
        if shell == "bash":
            d = base / "bash-completion" / "completions"
            d.mkdir(parents=True, exist_ok=True)
            out = d / self.prog
            content = self.emit_bash()
        elif shell == "zsh":
            d = base / "zsh" / "site-functions"
            d.mkdir(parents=True, exist_ok=True)
            out = d / f"_{self.prog}"
            content = self.emit_zsh()
        else:  # fish
            d = base / "fish" / "vendor_completions.d"
            d.mkdir(parents=True, exist_ok=True)
            out = d / f"{self.prog}.fish"
            content = self.emit_fish()
        if out.exists() and not overwrite:
            raise FileExistsError(f"{out} already exists (pass overwrite=True to replace)")
        out.write_text(content, encoding="utf-8")
        return out

    # ---- Dispatch -----------------------------------------------------

    def emit(self, shell: str) -> str:
        """Emit a completion script for the given shell."""
        if shell == "bash":
            return self.emit_bash()
        if shell == "zsh":
            return self.emit_zsh()
        if shell == "fish":
            return self.emit_fish()
        raise ValueError(f"unsupported shell: {shell!r}")
